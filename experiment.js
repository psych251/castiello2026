/*
 * Psych 251 replication of Castiello et al. (2026), Experiment 3.
 * Castiello, Pitliya, Lametti & Murphy, Communications Psychology 4:93,
 * https://doi.org/10.1038/s44271-026-00433-8
 *
 * Design summary
 *   IV:     chatbot personality, within subjects: "mirror" (the participant's own BFI-44
 *           profile) vs "inverse" (6 − each trait mean). Every participant chats with both.
 *   DV:     affiliation per bot = mean of six post-chat ratings coded −2..+2, "distant" and
 *           "different" reversed. Saved on the `affiliation` trial as affiliation_mirror and
 *           affiliation_inverse.
 *   Trials: consent, BFI-44 (+1 attention check), task instructions, chat 1 (24 messages),
 *           chat 2 (24 messages), post-chat questionnaire, demographics, two optional
 *           free-text feedback questions (added for Pilot B; not part of the paper's design),
 *           debrief.
 *   Random: order (mirror first / inverse first) x name (mirror is Pat / mirror is Alex),
 *           simple random assignment, drawn by the chat service.
 *   Exclusions (preregistration, applied in the report): fewer than 8 turns in a chat, a
 *           failed attention check, or all five trait means exactly 3.
 *
 * The chats are generated by the chat service (server/), which scores the BFI, assigns the
 * bots, builds their prompts and talks to the model. This page never learns which bot is the
 * mirror, the scores, or the prompts: it receives only the two names and the replies. The
 * condition labels, scores and mirror/inverse affiliation are joined back on at export
 * (scripts/export.js). The earlier manual-relay version is kept in reference/manual-relay/.
 */

// ---------------------------------------------------------------------------
// Settings
// ---------------------------------------------------------------------------
window.TEMPLATE_VERSION = "0.1.0";

const EXPERIMENT = {
  // Firestore path: experiments/<id>/participants/... Change it for each phase so pilot and
  // real data never mix. Must match experiment_id in writeup/replication-report.qmd.
  // Pilot C (2026-10-27): invited non-naive testers, revised prompt and safeguards. Pilot B was
  // "castiello2026-pilot-b"; its records stay under that id and are never pooled with Pilot C.
  id: "castiello2026-pilot-c",

  // Trials per Firestore write. 1 = save every trial the moment it finishes. This study has
  // only about ten trials, so 1 is well inside the free tier.
  chunk_size: 1,

  // Also store the complete jsPsych dataset on the participant document at the end.
  save_full_data_at_end: true,

  // Prolific: if set, participants are redirected to Prolific when they finish. Pilot C testers
  // are invited directly, not through Prolific.
  prolific_completion_code: null,

  // Only people with an invite link (?invite=<code>, made with scripts/pilot-admin.js) can take
  // part. The page checks the code with the chat service before signing in or saving anything,
  // and takes it out of the address bar so it is never stored; the service checks it again and
  // counts its use when the chats are set up.
  invite_only: true,

  // Contact shown in consent and debrief.
  contact_email: "stanfordpsych251@gmail.com",

  // The chats are typed, which needs a physical keyboard; phones and tablets are turned away
  // before consent.
  requires_keyboard: true,

  // The chat service's address: the deployed Cloud Function,
  // "https://us-central1-<project id>.cloudfunctions.net/chat". Empty until it is deployed: with
  // no address, live runs stop at a "chat cannot connect" screen instead of carrying on without
  // chats. Test and local runs (?emulator=1) always use the same function in the local
  // emulators (`npm run dev`), whatever this says.
  // Chat length and message length are set in server/config.js.
  chat_endpoint: "https://us-central1-castiello2026-replication.cloudfunctions.net/chat",

  // BFI-44: how many of the 44 items a participant may leave blank and still continue
  // (must match max_bfi_skips in server/config.js).
  max_bfi_skips: 5,

  // Two optional free-text questions after demographics, added for Pilot B: what participants
  // understood the task to be, and anything they found confusing. Not affiliation items and not
  // used by any exclusion. The answers are exported only to the gitignored feedback.csv. Decide
  // before the main study whether to keep them.
  feedback_questions: true,

  // SUSPENSION (2026-10-27): participant testing is paused pending the protocol director's
  // review. While true, every visitor sees only "Study temporarily closed": the page stops
  // before signing in, creating a participant record, consent or the questionnaire. Set false
  // (and lift `suspended` in server/config.js) to reopen. Only test runs in the local emulators
  // may skip it, with ?emulator=1&ignore_suspension=1.
  suspended: false,
};

// The study explanation from the debrief (section 8), word for word. Also shown, with the true
// saving status, to anyone whose chats end early (a technical failure, leaving, a pause), so
// everyone who reached the chats is debriefed.
const DEBRIEF_ABOUT = "Thank you for your participation! This study investigates if people have different feelings of connection towards AI chatbots whose conversational styles remind them of their own characteristics or contrasting ones.";
const DEBRIEF_DESIGN = "The two chat partners are AI chatbots prompted with personality scores calculated from your answers to the personality survey. Your answers were used to influence the chatbot's conversational styles, there's no new model training based on it. We did not mention which chatbot corresponded to which personality profile in advance so that it won't influence your impression ratings, which will help us examine if and how people respond differently to the two profiles. ";

// True on anything with a mouse, trackpad, or stylus, including laptops with touchscreens.
function hasFinePointer() {
  return !!(window.matchMedia && window.matchMedia("(any-pointer: fine)").matches);
}

// `?emulator=1` sends data to the local emulator instead of the real project (used by
// `npm test`; start it yourself with `npm run emulators`).
const URL_PARAMS = new URLSearchParams(window.location.search);
// Only on this computer (npm run dev / npm test): on the published site ?emulator=1, and with it
// ignore_suspension, chat_server, cc and forced assignments, are ignored.
const ON_LOCALHOST = /^(localhost|127\.0\.0\.1)$/.test(window.location.hostname);
const USE_EMULATOR = ON_LOCALHOST && URL_PARAMS.get("emulator") === "1";
const CHUNK_SIZE = Number(URL_PARAMS.get("chunk_size")) || EXPERIMENT.chunk_size;
if (USE_EMULATOR && URL_PARAMS.get("cc")) EXPERIMENT.prolific_completion_code = URL_PARAMS.get("cc");
const IGNORE_SUSPENSION = USE_EMULATOR && URL_PARAMS.get("ignore_suspension") === "1";
// Test runs only: show the closed page as if EXPERIMENT.suspended were true.
if (USE_EMULATOR && URL_PARAMS.get("test_suspended") === "1") EXPERIMENT.suspended = true;

// ---------------------------------------------------------------------------
// Boot
// ---------------------------------------------------------------------------
(async function main() {
  const closedPage = (heading, text) => {
    document.body.innerHTML =
      '<div id="study-closed" class="jspsych-content" style="max-width:640px;margin:15vh auto;font:16px/1.6 system-ui,sans-serif;">' +
      "<h2>" + heading + "</h2><p>" + text + "</p>" +
      "<p>Questions: <a href=\"mailto:" + EXPERIMENT.contact_email + "\">" + EXPERIMENT.contact_email + "</a></p></div>";
  };
  // Before anything else: no sign-in, no record, no data.
  if (EXPERIMENT.suspended && !IGNORE_SUSPENSION) {
    closedPage("Study temporarily closed", "This study is not running at the moment. Nothing has been recorded. Please close this " +
      "window" + (EXPERIMENT.prolific_completion_code ? " and return the study on Prolific" : "") + ".");
    return;
  }

  // The chat service: the Cloud Function in the local emulators in test runs (`npm run dev` /
  // `npm test`), otherwise EXPERIMENT.chat_endpoint.
  const chatEndpoint = USE_EMULATOR
    ? (URL_PARAMS.get("chat_server") || "http://127.0.0.1:5001/demo-psych251/us-central1/chat")
    : EXPERIMENT.chat_endpoint;
  const testHeaders = IGNORE_SUSPENSION ? { "X-Test-Ignore-Suspension": "1" } : {};

  // Invite-only: check the link with the service before signing in, and keep the code out of
  // every saved record (the saver records the address's parameters when it starts).
  let invite = null;
  if (EXPERIMENT.invite_only) {
    invite = URL_PARAMS.get("invite");
    if (invite) {
      const u = new URL(window.location.href);
      u.searchParams.delete("invite");
      window.history.replaceState(null, "", u.toString());
    }
    const access = invite
      ? await new ChatClient({ endpoint: chatEndpoint, experiment_id: EXPERIMENT.id, headers: testHeaders, invite: invite }).access()
      : { ok: false, code: "invite_required" };
    if (!access.ok) {
      if (access.code === "invite_required" || access.code === "invite_invalid") {
        closedPage("This link cannot be used", "This study is open only to invited testers, and this link is not valid or has " +
          "already been used. Nothing has been recorded.");
      } else if (access.code === "network" || access.code === "pause_check_failed" || access.code === "not_configured") {
        closedPage("Study unavailable", "The study cannot be reached right now. Nothing has been recorded. Please try again later.");
      } else {
        closedPage("Study temporarily closed", "This study is not running at the moment. Nothing has been recorded. Please close this window.");
      }
      return;
    }
  }

  const C = window.Castiello;
  const deviceSupported = !EXPERIMENT.requires_keyboard || hasFinePointer();

  const saver = await DataSaver.init({
    experiment_id: EXPERIMENT.id,
    chunk_size: CHUNK_SIZE,
    save_full_data_at_end: EXPERIMENT.save_full_data_at_end,
    use_emulator: USE_EMULATOR,
    contact_email: EXPERIMENT.contact_email,
  });
  window.__saver = saver; // for debugging and the automated test

  // Chats need both the service and a signed-in database connection; without either the
  // participant is told straight after consent, before doing any work.
  const client = new ChatClient({ endpoint: chatEndpoint, saver: saver, experiment_id: EXPERIMENT.id,
    headers: testHeaders, invite: invite });
  const chatMode = saver.mode === "offline" ? "unavailable: no database connection"
    : !chatEndpoint ? "unavailable: chat service not configured"
    : (await client.health()) ? "live" : "unavailable: chat service unreachable";

  saver.updateParticipant({ device_supported: deviceSupported, requires_keyboard: EXPERIMENT.requires_keyboard });

  if (!deviceSupported) {
    document.body.innerHTML =
      '<div id="device-unsupported" class="jspsych-content" style="max-width:640px;margin:15vh auto;font:16px/1.6 system-ui,sans-serif;">' +
      "<h2>Please use a computer</h2>" +
      "<p>This study needs a computer with a physical keyboard, because you will be typing " +
      "messages in two chats. Phones and tablets cannot be used.</p>" +
      "<p>Please reopen this link on a laptop or desktop computer. If you were sent here from " +
      "Prolific, you can return the study and take it later on a computer; nothing has been recorded " +
      "against you.</p>" +
      "<p>Questions: <a href=\"mailto:" + EXPERIMENT.contact_email + "\">" + EXPERIMENT.contact_email + "</a></p></div>";
    return;
  }

  const jsPsych = initJsPsych({
    show_progress_bar: true,
    auto_update_progress_bar: true,
    on_data_update: (trial) => saver.onTrial(trial),
    on_finish: async () => {
      const el = jsPsych.getDisplayElement();
      el.innerHTML = '<div id="finish-message"><p class="thanks">Saving your responses…</p></div>';
      const consentRow = jsPsych.data.get().filter({ task: "consent" }).values()[0];
      const consented = !consentRow || consentRow.consented !== false;
      const unavailable = jsPsych.data.get().filter({ task: "chat_unavailable" }).count() > 0
        || jsPsych.data.get().filter({ task: "chat_setup", setup_ok: false }).count() > 0;
      const chatFailed = jsPsych.data.get().filter({ task: "chat", ended_reason: "failed" }).count() > 0;
      const leftAfterStop = jsPsych.data.get().filter({ task: "chat", ended_reason: "withdrew_after_safety_stop" }).count() > 0;
      const withdrew = leftAfterStop || jsPsych.data.get().filter({ task: "chat", ended_reason: "withdrew" }).count() > 0;
      const paused = jsPsych.data.get().filter({ task: "chat", ended_reason: "paused" }).count() > 0;
      // A study that stopped early is saved as not completed, so it can never be counted as a
      // finished session. A chat ended by the safety check is not an early end when the
      // participant went on, so `completed` says only that the survey was finished, never that
      // both chats ran in full: see chat1_ended_reason / chat2_ended_reason and safety_stop_any.
      const endedEarly = !consented ? "declined_consent" : leftAfterStop ? "withdrew_after_safety_stop" : withdrew ? "withdrew" : paused ? "paused"
        : unavailable ? "chat_unavailable" : chatFailed ? "chat_failed" : null;
      const result = await saver.finish(jsPsych, endedEarly ? { completed: false, ended_early: endedEarly } : {});
      const msg = document.getElementById("finish-message");

      if (!consented) {
        msg.innerHTML = "<h2 class='thanks'>Thank you</h2><p class='thanks'>You chose not to participate. " +
          "You may close this window" + (EXPERIMENT.prolific_completion_code ? " and return the study on Prolific" : "") + ".</p>";
        return;
      }
      // Chats that ended early: why, what was saved (true status), the debrief's explanation of
      // the study, and the contact. No completion code: these sessions are not complete.
      const earlyExit = (heading, why) => {
        msg.innerHTML =
          "<h2 class='thanks'>" + heading + "</h2>" +
          "<p class='thanks'>" + why + "</p>" +
          "<p class='thanks early-exit-saving'>" + (result.ok
            ? "Your answers up to this point have been saved. Nothing after this point was recorded."
            : "Some of your answers could not be saved because of a connection problem. Please use the download below.") + "</p>" +
          "<h3 class='thanks'>About this study</h3>" +
          "<p class='thanks'>" + DEBRIEF_ABOUT + "</p><p class='thanks'>" + DEBRIEF_DESIGN + "</p>" +
          "<p class='thanks'>You may close this window. If you have questions or concerns, contact " +
          "<a href=\"mailto:" + EXPERIMENT.contact_email + "\">" + EXPERIMENT.contact_email + "</a>.</p>";
      };
      if (leftAfterStop) return earlyExit("You have left the study", "You left after the chat was ended early by the study's automatic check.");
      if (paused) return earlyExit("You have left the study", "The researchers have paused the study, so it ended early.");
      if (withdrew) return earlyExit("You have left the study", "You chose to stop the study.");
      if (unavailable) {
        msg.innerHTML = "<h2 class='thanks'>Sorry</h2><p class='thanks'>The chat could not connect, so the " +
          "study cannot continue. You may close this window. Questions: " + EXPERIMENT.contact_email + "</p>";
        return;
      }
      if (chatFailed) {
        return earlyExit("The chat could not continue", "A technical problem stopped the chat, so the study has ended early. " +
          "This was not caused by anything you did.");
      }
      if (result.ok && EXPERIMENT.prolific_completion_code && !USE_EMULATOR) {
        msg.innerHTML = "<p class='thanks'>Saved. Returning you to Prolific…</p>";
        window.location.href =
          "https://app.prolific.com/submissions/complete?cc=" + EXPERIMENT.prolific_completion_code;
        return;
      }
      msg.innerHTML =
        "<h2 class='thanks'>All done</h2>" +
        (result.ok ? "<p class='thanks'>Your responses were saved. Thank you for participating!</p>" : "") +
        (EXPERIMENT.prolific_completion_code
          ? "<p class='thanks'>Your completion code is <strong>" + EXPERIMENT.prolific_completion_code + "</strong>.</p>"
          : "");
    },
  });

  jsPsych.data.addProperties({
    // Must be the run-scoped document id, so trial rows join to participants.csv on export.
    participant_id: saver.docId,
    prolific_pid: saver.params.PROLIFIC_PID || null,
    experiment_id: EXPERIMENT.id,
    chat_mode: chatMode,
  });
  saver.updateParticipant({ chat_mode: chatMode, chat_status: "not_started" });

  // Test runs may fix the assignment with ?order=mirror-first|inverse-first&mirror_name=Pat|Alex.
  // Only the function in the local emulators honours it.
  const forcedAssignment = USE_EMULATOR && (URL_PARAMS.get("order") || URL_PARAMS.get("mirror_name"))
    ? { order: URL_PARAMS.get("order"), mirror_name: URL_PARAMS.get("mirror_name") } : null;
  const botName = (index) => client.session.chats[index - 1].bot_name;
  // What the chat plugins get: two plain functions. (jsPsych copies object parameters, and the
  // client itself holds the database connection, which cannot be copied.)
  const chatApi = {
    startSession: (answers, force) => client.startSession(answers, force),
    turn: (chatIndex, seq, text) => client.turn(chatIndex, seq, text),
    end: (chatIndex, reason) => client.end(chatIndex, reason),
  };

  // -------------------------------------------------------------------------
  // 1. Consent (course-wide IRB text; edit only the contact address)
  // -------------------------------------------------------------------------
  const consent = {
    type: jsPsychHtmlButtonResponse,
    stimulus: `
      <div class="consent">
        <h2>Consent</h2>
        <p>By answering the following questions, you are participating in a study being performed by
        cognitive scientists in the Stanford Department of Psychology. If you have questions about
        this research, please contact us at <a href="mailto:${EXPERIMENT.contact_email}">${EXPERIMENT.contact_email}</a>.
        You must be at least 18 years old to participate. Your participation in this research is
        voluntary. You may decline to answer any or all of the following questions. You may decline
        further participation, at any time, without adverse consequences. Your anonymity is assured;
        the researchers who have requested your participation will not receive any personal
        information about you.</p>
      </div>`,
    choices: ["I agree to participate", "I do not agree"],
    data: { task: "consent" },
    on_finish: (data) => {
      data.consented = data.response === 0;
      if (!data.consented) jsPsych.abortExperiment();
    },
  };

  // Shown only if the page could not reach the database or the chat service.
  const chatUnavailable = {
    timeline: [{
      type: jsPsychHtmlButtonResponse,
      stimulus: "<h2>The chat cannot connect</h2><p>This study needs a live connection for its chats, and " +
        "the connection failed. Please close this window; you do not need to do anything else.</p>",
      choices: ["Close"],
      data: { task: "chat_unavailable" },
      on_finish: () => jsPsych.abortExperiment(),
    }],
    conditional_function: () => chatMode !== "live",
  };

  // -------------------------------------------------------------------------
  // 2. BFI-44 (one page; up to max_bfi_skips items may be left blank)
  // -------------------------------------------------------------------------
  const bfiRows = [];
  for (const item of C.BFI_ITEMS) {
    bfiRows.push({ value: item.id, text: item.text });
    if (item.number === C.ATTENTION_CHECK.after_item) bfiRows.push({ value: C.ATTENTION_CHECK.id, text: C.ATTENTION_CHECK.text });
  }
  const bfi = {
    type: jsPsychSurvey,
    survey_json: {
      showQuestionNumbers: "off",
      widthMode: "responsive",
      completeText: "Continue",
      pages: [{
        elements: [{
          type: "matrix",
          name: "bfi",
          title: C.BFI_STEM,
          description: "Here are a number of characteristics that may or may not apply to you. Please indicate " +
            "the extent to which you agree or disagree with each statement. You may leave up to " +
            EXPERIMENT.max_bfi_skips + " statements blank.",
          columns: C.BFI_SCALE,
          columnMinWidth: "88px",
          rowTitleWidth: "34%",
          rows: bfiRows,
          alternateRows: true,
        }],
      }],
    },
    survey_function: (survey) => {
      window.__survey = survey; // lets the automated test fill the page quickly
      survey.onValidateQuestion.add((sender, options) => {
        if (options.name !== "bfi") return;
        const v = options.value || {};
        const blank = C.BFI_ITEMS.filter((i) => v[i.id] === undefined || v[i.id] === null).length;
        if (blank > EXPERIMENT.max_bfi_skips) {
          options.error = "You have left " + blank + " statements blank. You may leave at most " +
            EXPERIMENT.max_bfi_skips + " blank; please answer at least " + (C.BFI_ITEMS.length - EXPERIMENT.max_bfi_skips) + ".";
        }
      });
    },
    data: { task: "bfi" },
    on_finish: (data) => {
      // Scoring happens on the chat service, so the five scores never reach this page.
      const answers = (data.response || {}).bfi || {};
      data.bfi_raw = {};
      for (const item of C.BFI_ITEMS) data.bfi_raw[item.id] = answers[item.id] === undefined ? null : answers[item.id];
      data.bfi_n_skipped = Object.values(data.bfi_raw).filter((x) => x === null).length;
      data.attention_check_response = answers[C.ATTENTION_CHECK.id] === undefined ? null : answers[C.ATTENTION_CHECK.id];
      saver.updateParticipant({ bfi_done: true });
    },
  };

  // Sends the BFI answers to the chat service, which scores them and assigns the two bots.
  const chatSetup = {
    type: jsPsychChatSetup,
    client: chatApi,
    get_answers: () => {
      const bfiRow = jsPsych.data.get().filter({ task: "bfi" }).values()[0];
      return Object.assign({}, bfiRow.bfi_raw, { [C.ATTENTION_CHECK.id]: bfiRow.attention_check_response });
    },
    force: forcedAssignment,
    save_trial_parameters: { client: false },
    data: { task: "chat_setup" },
    on_finish: (data) => {
      if (!data.setup_ok) jsPsych.abortExperiment();
    },
  };

  // -------------------------------------------------------------------------
  // 3. Task instructions (Supplementary Information, "Task instructions", verbatim)
  // -------------------------------------------------------------------------
  const instructions = {
    type: jsPsychInstructions,
    pages: [
      `<div class="instructions">
       <p>Thank you for participating in this study. We will ask you to interact with two chatbots.</p>
       <p>Each chat will take around 10 minutes.</p>
       <p>Your goal is to learn as much as you can about each chatbot, asking them whatever questions
       you’d find necessary to determine whether you get on with them if they were a real person.</p>
       <p>After chatting with both chatbots, you will be asked about your experience with the chatbots.</p>
       </div>`,
    ],
    show_clickable_nav: true,
    data: { task: "instructions" },
  };

  // -------------------------------------------------------------------------
  // 4–5. The two chats
  // -------------------------------------------------------------------------
  function chatBlock(index) {
    const intro = {
      type: jsPsychHtmlButtonResponse,
      stimulus: () => {
        const total = client.session.messages_per_chat;
        return `<div class="instructions">
        <h2>${index === 1 ? "Your first chat" : "Your second chat"}</h2>
        <p>You will now chat with <strong>${botName(index)}</strong>. ${botName(index)} will send the first message.</p>
        <p>The chat ends after ${total} messages in total
        (${Math.floor(total / 2)} from you). Please wait for each reply before writing again.</p>
      </div>`;
      },
      choices: ["Start chat"],
      data: { task: "chat_intro", chat_index: index },
      on_start: (trial) => { trial.data.bot_name = botName(index); },
      on_finish: () => saver.updateParticipant({ chat_status: "chat" + index }),
    };
    const chat = {
      type: jsPsychLiveChat,
      chat_index: index,
      client: chatApi,
      save_trial_parameters: { client: false },
      data: { task: "chat" },
      on_start: (trial) => {
        trial.bot_name = botName(index);
        trial.total_messages = client.session.messages_per_chat;
        trial.max_chars = client.session.max_message_chars;
      },
      on_finish: (data) => {
        // Exposure and safety status, kept on the participant record for good: chat_status is
        // progress and later steps overwrite it. (The chat service's own record, private/session
        // chat*_safety_stopped_at and chat*_completed_at, is the authoritative copy.)
        const stoppedHere = ["safety_stop", "withdrew_after_safety_stop"].includes(data.ended_reason);
        saver.updateParticipant(Object.assign({
          ["chat" + index + "_ended_reason"]: data.ended_reason,
          ["chat" + index + "_n_messages"]: data.n_messages,
        }, stoppedHere ? { safety_stop_any: true } : {}));
        if (["failed", "withdrew", "withdrew_after_safety_stop", "paused"].includes(data.ended_reason)) {
          saver.updateParticipant({ chat_status: "chat" + index + "_" + data.ended_reason });
          jsPsych.abortExperiment();
        } else if (data.ended_reason === "safety_stop") {
          saver.updateParticipant({ chat_status: "chat" + index + "_safety_stop" });
        }
      },
    };
    return [intro, chat];
  }

  // -------------------------------------------------------------------------
  // 6. Post-chat questionnaire (Supplementary Information, "Post chat questionnaire")
  // -------------------------------------------------------------------------
  const affiliation = {
    type: jsPsychSurvey,
    survey_json: {
      showQuestionNumbers: "off",
      widthMode: "responsive",
      completeText: "Continue",
      pages: [{
        elements: [
          {
            type: "html",
            name: "aff_intro",
            html: `<p>Thank you for participating in our study. We have a few questions to match you with the ideal chatbot.</p>
              <p>Choose the answer that shows how much you agree or disagree with each of the following statements about
              the Chatbots you have just communicated with, as if they were a real-life individual.</p>
              <p>As a reminder, your first chat was with BOT1, and the second chat was with BOT2.</p>`,
          },
        ].concat(C.AFFILIATION_ITEMS.map((item) => ({
          type: "matrix",
          name: "aff_" + item.id,
          title: item.text + ":",
          columns: C.AFFILIATION_SCALE,
          columnMinWidth: "88px",
          rowTitleWidth: "18%",
          rows: [{ value: "chat1", text: "BOT1" }, { value: "chat2", text: "BOT2" }],
        }))),
      }],
    },
    survey_function: (survey) => { window.__survey = survey; },
    // The bot names are known only once the chat service has assigned them.
    on_start: (trial) => {
      trial.survey_json = JSON.parse(JSON.stringify(trial.survey_json)
        .replace(/BOT1/g, botName(1)).replace(/BOT2/g, botName(2)));
    },
    data: { task: "affiliation" },
    on_finish: (data) => {
      // One mean per chat. Which chat was the mirror is joined on at export, so
      // affiliation_mirror / affiliation_inverse appear in trials.csv as before.
      const s = C.scoreAffiliation(data.response, { chat1: "chat1", chat2: "chat2" });
      Object.assign(data, {
        affiliation_coded: s.coded,
        affiliation_chat1: s.affiliation_chat1,
        affiliation_chat2: s.affiliation_chat2,
        affiliation_n_items_chat1: s.n_items_chat1,
        affiliation_n_items_chat2: s.n_items_chat2,
      });
      saver.updateParticipant({ chat_status: "done" });
    },
  };

  // -------------------------------------------------------------------------
  // 7. Demographics (the paper reports age and gender; "What is your gender?" is its wording)
  // -------------------------------------------------------------------------
  const demographics = {
    type: jsPsychSurvey,
    survey_json: {
      showQuestionNumbers: "off",
      widthMode: "responsive",
      completeText: "Continue",
      pages: [{
        elements: [
          // The consent text promises participants may decline any question, so nothing here is required.
          { type: "text", name: "age", title: "How old are you?", inputType: "number", min: 18, max: 120 },
          {
            type: "radiogroup", name: "gender", title: "What is your gender?",
            choices: ["Woman", "Man", "Non-binary"], showOtherItem: true, showNoneItem: true, noneText: "Prefer not to say",
          },
          { type: "boolean", name: "native_english", title: "Is English your first language?", labelTrue: "Yes", labelFalse: "No" },
        ],
      }],
    },
    data: { task: "demographics" },
  };

  // -------------------------------------------------------------------------
  // 7b. Pilot feedback (optional free text; see EXPERIMENT.feedback_questions)
  // -------------------------------------------------------------------------
  const feedback = {
    timeline: [{
      type: jsPsychSurvey,
      survey_json: {
        showQuestionNumbers: "off",
        widthMode: "responsive",
        completeText: "Continue",
        pages: [{
          elements: [
            { type: "comment", name: "task_understanding", rows: 3, maxLength: 2000,
              title: "In your own words, what were you asked to do during the chats?" },
            { type: "comment", name: "confusion", rows: 3, maxLength: 2000,
              title: "Was anything about the instructions or study confusing? If so, please describe." },
          ],
        }],
      },
      data: { task: "feedback" },
    }],
    conditional_function: () => EXPERIMENT.feedback_questions,
  };

  // -------------------------------------------------------------------------
  // 8. Debrief
  // -------------------------------------------------------------------------
  const debrief = {
    type: jsPsychHtmlButtonResponse,
    stimulus: `
      <h2>Debrief</h2>
      <p>${DEBRIEF_ABOUT}</p>
      <p>${DEBRIEF_DESIGN}</p>
      <p>Your questionnaire answers, chat messages, and ratings were recorded for this research. Thank you for your time and contribution.</p>
      <p>If you have questions about this research, contact
      <a href="mailto:${EXPERIMENT.contact_email}">${EXPERIMENT.contact_email}</a>.
      Press the button to save your responses and finish.</p>`,
    choices: ["Finish"],
    data: { task: "debrief" },
  };

  await jsPsych.run([
    consent,
    chatUnavailable,
    bfi,
    chatSetup,
    instructions,
    ...chatBlock(1),
    ...chatBlock(2),
    affiliation,
    demographics,
    feedback,
    debrief,
  ]);
})();
